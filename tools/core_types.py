#!/usr/bin/env python3
"""Write profiles/core-types.json: the node and edge types of the EM core.

    python3 tools/core_types.py <path to an s3Dgraphy checkout>

A profile type must be the SPECIES of a core type (profiles/SPEC.md §4). The
tests check every `specializes` against this list, so the list must come from
the core and never be written by hand: this script reads s3Dgraphy's
generated node registry and its connections datamodel, and records which
versions it read. Rerun it when the core changes.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "profiles" / "core-types.json"


def main(argv):
    if not argv:
        print(__doc__)
        return 2
    s3d = Path(argv[0]).expanduser()
    cfg = s3d / "src" / "s3dgraphy" / "JSON_config"
    reg = json.loads((cfg / "node_registry.generated.json").read_text(encoding="utf-8"))
    con = json.loads((cfg / "s3Dgraphy_connections_datamodel.json").read_text(encoding="utf-8"))
    commit = subprocess.run(["git", "-C", str(s3d), "log", "-1", "--format=%h", "--", "src/s3dgraphy/JSON_config"],
                            capture_output=True, text=True).stdout.strip() or "unknown"
    nodes = sorted({v["node_type"] for v in reg["node_types"].values()
                    if v.get("node_type") and v["node_type"] not in ("None", "unknown")})
    edges = sorted(con["edge_types"])
    out = {
        "_comment": "GENERATED by tools/core_types.py from s3Dgraphy — do not edit by hand. "
                    "The runtime node_type and edge_type names of the EM core a profile type may specialise.",
        "source": {"repository": "https://github.com/ExtendedMatrix/s3Dgraphy", "commit": commit,
                   "nodes": reg["s3Dgraphy_data_model_version"],
                   "connections": con["s3Dgraphy_connections_model_version"]},
        "node_types": nodes,
        "edge_types": edges,
    }
    OUT.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(REPO)}: {len(nodes)} node types, {len(edges)} edge types "
          f"(nodes {out['source']['nodes']}, connections {out['source']['connections']}, s3Dgraphy {commit})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
